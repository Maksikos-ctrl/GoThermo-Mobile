/// [text] without its last emoji or character (a whole emoji with its joiners
/// and skin tone goes in one step).
String dropLastGrapheme(String text) {
  if (text.isEmpty) return text;
  final runes = text.runes.toList();
  bool joiner(int r) => r == 0x200D || r == 0xFE0F || (r >= 0x1F3FB && r <= 0x1F3FF);
  while (runes.isNotEmpty) {
    final last = runes.removeLast();
    final glued = joiner(last) || (runes.isNotEmpty && runes.last == 0x200D);
    if (!glued) break;
  }
  return String.fromCharCodes(runes);
}
